import assert from 'node:assert/strict';
import fs from 'node:fs';
import { loadProjectModule, loadQuotationModule } from './quotation-test-modules.mjs';
import { fillInvoice } from './invoice-fixtures.mjs';
const m = loadQuotationModule('model'), d = loadProjectModule('lib/documents/model.ts'), i = loadProjectModule('lib/documents/invoice-template.ts'), s = loadQuotationModule('storage');
const workspace = m.emptyWorkspace(), blank = d.createBusinessDocument('invoice', workspace);
assert.ok(d.documentErrors(blank).length);
assert.equal(i.invoiceItems(blank)[0].amount, '');
assert.equal(i.invoiceValue(blank, 'UPI_ID'), '', 'Reference payment address must not be copied into new invoices');
const invoice = fillInvoice(m.copy(blank));
assert.deepEqual(d.documentErrors(invoice), []);
assert.deepEqual(i.invoiceTotals(invoice), { subtotal:1650000, base:1650000, tax:0, total:1650000, mode:'none', rate:0 });
let taxed = i.setInvoiceValue(i.setInvoiceValue(invoice, 'TAX_MODE', 'exclusive'), 'TAX_RATE', '18');
assert.equal(i.invoiceTotals(taxed).total, 1947000);
taxed = i.setInvoiceValue(taxed, 'TAX_MODE', 'inclusive');
assert.equal(i.invoiceTotals(taxed).total, 1650000);
assert.equal(i.invoiceTotals(taxed).base + i.invoiceTotals(taxed).tax, 1650000);
const rounding = i.setInvoiceItems(taxed, [{ id:m.uid(), service:'Small amount', scope:'Rounding', amount:'0.03' }]);
assert.equal(i.invoiceTotals(rounding).tax, 0);
assert.throws(() => i.invoiceTotals(i.setInvoiceValue(taxed, 'TAX_RATE', '101')), /Tax rate/);
assert.throws(() => i.invoiceTotals(i.setInvoiceItems(invoice, [{id:m.uid(),service:'Invalid',scope:'Invalid',amount:'-1'}])), /amount/);
assert.ok(d.documentErrors(i.setInvoiceValue(invoice, 'DUE_DATE', '2026-02-30')).length);
const uri = new URL(i.invoicePaymentUri(invoice, i.invoiceTotals(invoice).total));
assert.equal(uri.searchParams.get('am'), '16500.00');
assert.equal(uri.searchParams.get('pa'), 'example@upi');
assert.equal(uri.searchParams.get('tn'), invoice.number);
const bank = i.setInvoiceValue(i.setInvoiceValue(invoice, 'UPI_ID', ''), 'BANK_DETAILS', 'Bank: Example Bank\nAccount: 000000000\nIFSC: EXAMPLE0000');
assert.deepEqual(d.documentErrors(bank), []);
assert.equal(i.invoicePaymentUri(bank, 1650000), '');
const final = d.finaliseDocument(invoice); workspace.documents.push(final);
assert.deepEqual(s.importBackup(JSON.stringify(workspace)), workspace);
const corrupt = m.copy(workspace); corrupt.documents[0].status = 'draft'; corrupt.documents[0].fields.find(field=>field.placeholder.startsWith('INVOICE_ITEM_')).value = 'invalid';
assert.throws(()=>s.importBackup(JSON.stringify(corrupt)), 'Malformed invoice rows must not crash the editor after import');
invoice.client.business = 'Changed'; assert.equal(final.client.business, 'Example Beverages');
const fonts = Object.fromEntries(fs.readdirSync('public/admin-assets/fonts').filter(name=>name.endsWith('.ttf')).map(name=>[name, fs.readFileSync(`public/admin-assets/fonts/${name}`).toString('base64')]));
const {generateBusinessPdf} = loadProjectModule('lib/documents/pdf.ts');
fs.mkdirSync('outputs/invoice-qa',{recursive:true});
const long = m.copy(final); long.status='draft';
const longInvoice = i.setInvoiceItems(long, Array.from({length:12},(_,n)=>({id:m.uid(),service:`Service ${n+1}`,scope:'An agreed scope with deliverables and handover. '.repeat(18),amount:'1000'})));
for (const [name,doc,options] of [['blank',blank,{preview:true}],['filled',final,{}],['print',final,{blackAndWhite:true}],['bank',bank,{}],['long',longInvoice,{}]]) {
  const result = await generateBusinessPdf(doc,{fontData:fonts,...options});
  fs.writeFileSync(`outputs/invoice-qa/${name}.pdf`,Buffer.from(result.pdf.output('arraybuffer')));
  if (name==='filled') assert.equal(result.pages,1,'Ordinary reference-style invoice should fit one page');
  if (name==='long') assert.ok(result.pages>1);
  console.log(`${name}: ${result.pages} pages`);
}
console.log('Invoice calculations, validation, QR payload, snapshots, backup and PDF tests passed.');
